  function translateValue(value) {
    if (!value) return value;
    const leading = value.match(/^\s*/)[0];
    const trailing = value.match(/\s*$/)[0];
    const source = value.trim();
    if (!source) return value;
    if (locale === "zh-CN") return chinese[source] ? `${leading}${chinese[source]}${trailing}` : value;
    if (english[source]) return `${leading}${english[source]}${trailing}`;
    for (const [pattern, replacement] of patterns) {
      if (pattern.test(source)) return `${leading}${source.replace(pattern, replacement)}${trailing}`;
    }
    return value;
  }

  function shouldSkip(node) {
    const element = node.nodeType === Node.ELEMENT_NODE ? node : node.parentElement;
    return Boolean(element?.closest(protectedContent));
  }

  function translateTextNode(node, resetSource = false) {
    if (shouldSkip(node)) return;
    if (resetSource || !textSources.has(node)) textSources.set(node, node.nodeValue);
    const source = textSources.get(node);
    const translated = translateValue(source);
    if (node.nodeValue !== translated) node.nodeValue = translated;
  }

  function translateElement(element, resetSource = false) {
    if (!(element instanceof Element) || element.matches("[data-language-toggle]")) return;
    if (!attributeSources.has(element)) attributeSources.set(element, {});
    const sources = attributeSources.get(element);
    attributes.forEach((attribute) => {
      if (!element.hasAttribute(attribute)) return;
      if (resetSource || !(attribute in sources)) sources[attribute] = element.getAttribute(attribute);
      const source = sources[attribute];
      const translated = translateValue(source);
      if (element.getAttribute(attribute) !== translated) element.setAttribute(attribute, translated);
    });
  }

